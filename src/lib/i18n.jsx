const LanguageContext = createContext(null);

function readLanguage() {
  try {
    return window.localStorage.getItem("rodas.language") === "am" ? "am" : "en";
  } catch (error) {
    console.warn("Unable to read the saved language preference:", error);
    return "en";
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(readLanguage);
  const locale = language === "am" ? "am-ET" : "en-US";
  const t = (text, values = {}) => {
    const translated = translations[language]?.[text] || text;
    return translated.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
  };

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = "ltr";
    try {
      window.localStorage.setItem("rodas.language", language);
    } catch (error) {
      console.warn("Unable to save the language preference:", error);
    }
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, locale, t }), [language, locale]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within a LanguageProvider.");
  return context;
}

export function LanguagePicker({ className = "" }) {
  const { language, setLanguage, t } = useLanguage();
  return <label className={`language-picker ${className}`}>
    <Languages size={16} aria-hidden="true" />
    <span className="sr-only">{t("Language")}</span>
    <select aria-label={t("Language")} value={language} onChange={(event) => setLanguage(event.target.value)}>
      <option value="en">English</option>
      <option value="am">አማርኛ</option>
    </select>
  </label>;
}
